/**
 * Deterministic checks on AI-written content. Anything that fails here is never published.
 * See PLAN.md, Milestone 2, Validation.
 */
import type { Segment, Tier } from '../../src/lib/types.ts';
import { segmentsToText } from './furigana.ts';
import { allKanjiRead, findTarget, type Target, type Tokenizer, toSegments } from './tokenizer.ts';

export const TIERS: Tier[] = ['beginner', 'intermediate', 'advanced'];
export const SENTENCES_PER_TIER = 2;

/** Japanese sentence length (characters) per tier: [min, max]. */
export const TIER_LENGTH: Record<Tier, [number, number]> = {
  beginner: [6, 25],
  intermediate: [10, 40],
  advanced: [15, 60],
};
export const DEFINITION_MAX = 80;
export const ENGLISH_MAX = 200;

/** Kana, kanji, Japanese punctuation and digits. No Latin letters (no romaji), no spaces. */
const JA_ALLOWED = /^[\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Han}ー々〆ヶ、。！？「」『』（）・〜…0-9０-９]+$/u;
const EN_ALLOWED = /^[\x20-\x7E‘’“”–—…éè]+$/;

/**
 * Small backstop for clearly unsuitable words. The prompt and the verification pass do the
 * real work on tone and topic; this only catches what must never slip through.
 */
const BLOCKLIST_JA = ['死ね', '殺す', '殺せ', '殺し', '自殺', 'くたばれ', 'ちくしょう', 'セックス', '覚醒剤'];
const BLOCKLIST_EN = /\b(kill(ed|ing|s)?|suicide|fuck\w*|shit\w*|bitch\w*|nazis?)\b/i;

export interface GeneratedSentence {
  ja: string;
  en: string;
}
export interface Generated {
  /** 0-based index of the JMdict meaning the content uses (shown as the English definition). */
  sense?: number;
  definition_ja: string;
  sentences: Record<Tier, GeneratedSentence[]>;
}

export interface CheckedSentence {
  segments: Segment[];
  en: string;
}
export interface Checked {
  definitionSegments: Segment[];
  sentences: Record<Tier, CheckedSentence[]>;
}

export function checkJapanese(text: string, label: string): string[] {
  const problems: string[] = [];
  if (!text) return [`${label}: empty`];
  if (/[A-Za-zＡ-Ｚａ-ｚ]/.test(text)) problems.push(`${label}: contains Latin letters (no romaji allowed)`);
  else if (!JA_ALLOWED.test(text)) problems.push(`${label}: contains characters other than kana, kanji and Japanese punctuation`);
  const blocked = BLOCKLIST_JA.find((w) => text.includes(w));
  if (blocked) problems.push(`${label}: contains blocked word ${blocked}`);
  return problems;
}

export function checkEnglish(text: string, label: string): string[] {
  const problems: string[] = [];
  if (!text.trim()) return [`${label}: empty English translation`];
  if (text.length > ENGLISH_MAX) problems.push(`${label}: English translation longer than ${ENGLISH_MAX} characters`);
  if (!EN_ALLOWED.test(text)) problems.push(`${label}: English translation contains unexpected characters`);
  if (BLOCKLIST_EN.test(text)) problems.push(`${label}: English translation contains a blocked word`);
  return problems;
}

/** 何 directly followed by kanji (何世代, 何人, 何時): the tokenizer often gives なに where なん is right. */
const hasAmbiguousNani = (segments: Segment[]) =>
  segments.some(([text], i) => text.endsWith('何') && /^[\p{Script=Han}]/u.test(segments[i + 1]?.[0] ?? ''));

/** Number of sentences, counted by sentence-ending punctuation. */
const sentenceCount = (text: string) => (text.match(/[。！？]+/g) ?? []).length + (/[。！？]$/.test(text) ? 0 : 1);

/**
 * Run every deterministic check. Returns problems (empty = pass) and, when it passes,
 * the content with furigana segments generated by the tokenizer.
 */
export function validate(gen: Generated, target: Target, tokenizer: Tokenizer): { problems: string[]; checked?: Checked } {
  const problems: string[] = [];

  // Simple-Japanese definition: short, plain, doesn't just repeat the word.
  const def = gen.definition_ja.trim();
  problems.push(...checkJapanese(def, 'definition_ja'));
  if ([...def].length > DEFINITION_MAX) problems.push(`definition_ja: longer than ${DEFINITION_MAX} characters`);
  if (sentenceCount(def) > 2) problems.push('definition_ja: more than 2 sentences');
  if (def.includes(target.text)) problems.push(`definition_ja: uses the word ${target.text} itself`);
  const definitionSegments = toSegments(tokenizer.tokenize(def));
  if (!allKanjiRead(definitionSegments)) problems.push('definition_ja: has kanji the tokenizer could not read');
  if (hasAmbiguousNani(definitionSegments)) problems.push("definition_ja: 何 before a kanji word (なに/なん can't be read reliably); rephrase");

  const sentences = {} as Record<Tier, CheckedSentence[]>;
  const seen = new Set<string>();
  for (const tier of TIERS) {
    const list = gen.sentences[tier] ?? [];
    if (list.length !== SENTENCES_PER_TIER) problems.push(`${tier}: expected ${SENTENCES_PER_TIER} sentences, got ${list.length}`);
    sentences[tier] = [];
    list.forEach((s, i) => {
      const label = `${tier} sentence ${i + 1}`;
      const ja = s.ja.trim();
      const [min, max] = TIER_LENGTH[tier];
      const length = [...ja].length;
      problems.push(...checkJapanese(ja, label), ...checkEnglish(s.en, label));
      if (length < min || length > max) problems.push(`${label}: ${length} characters, expected ${min}-${max}`);
      if (sentenceCount(ja) !== 1) problems.push(`${label}: must be exactly one sentence`);
      if (!/[。！？]$/.test(ja)) problems.push(`${label}: must end with 。, ！ or ？`);
      if (seen.has(ja)) problems.push(`${label}: duplicate sentence`);
      seen.add(ja);

      const tokens = tokenizer.tokenize(ja);
      if (!findTarget(tokens, target)) problems.push(`${label}: does not contain the word ${target.text} (in any form)`);
      const segments = toSegments(tokens, target);
      if (segmentsToText(segments) !== ja) problems.push(`${label}: furigana segments do not rebuild the sentence`);
      if (!allKanjiRead(segments)) problems.push(`${label}: has kanji the tokenizer could not read`);
      if (hasAmbiguousNani(segments)) problems.push(`${label}: 何 before a kanji word (なに/なん can't be read reliably); rephrase`);
      sentences[tier].push({ segments, en: s.en.trim() });
    });
  }

  return problems.length ? { problems } : { problems, checked: { definitionSegments, sentences } };
}
